// Verified in a real browser against a copy of the live database before this was committed:
//
//   * 24,202 -> 10,051 elements, 1,690 -> 683 KB, all 92 recipe cards present, 0 console errors
//   * "Show the other 512 steps" -> 457 -> 969 steps, exactly 512 with data-idx >= 20
//   * clicked ↔ scope on the step at index 270 (which cannot exist without the reveal) and
//     confirmed THE SERVER changed, then restored it
//
// That last check nearly recorded a false failure. A scope flip does NOT write a `scope` column
// on the step -- updateRecipeStepFields MOVES the step into the recipe's sibling of the other
// scope, changing recipe_id. Reading `step.scope` showed null both before and after and looked
// exactly like a dead button. The control that proves the click landed is which recipe now
// owns the step, which is what this test pins.
test('a scope flip is a MOVE between recipes, not a field write', () => {
  const i = APP.indexOf('const patchStep = async');
  assert.ok(i > 0);
  const flip = APP.slice(APP.indexOf("[data-flip-scope]"), APP.indexOf("[data-flip-scope]") + 400);
  assert.match(flip, /patchStep\(stepId, \{ scope: scope === 'company' \? 'ats' : 'company' \}/,
    'the flip sends the OPPOSITE scope; the server resolves it into a recipe move');
});
